-- Trigger 1 - je technik skolen na dane letadlo pred provedenim testu? --
CREATE OR REPLACE TRIGGER check_technik_skoleni
BEFORE INSERT ON provadi
FOR EACH ROW
DECLARE
    v_model_id letadlo.model_id%TYPE;
    v_count NUMBER;
BEGIN
    -- Model letadla, ktere se testuje --
    SELECT model_id INTO v_model_id
    FROM letadlo L JOIN test T ON L.vyrobni_cislo = T.vyrobni_cislo_letadla
    WHERE T.id = :NEW.id_testu;

    -- Kontrola platnosti skoleni technika --
    SELECT COUNT(*) INTO v_count
    FROM vyskolen
    WHERE rodne_cislo = :NEW.rodne_cislo
        AND model_id = v_model_id
        AND platnost_skoleni >= :NEW.datum_provedeni;

    IF v_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Technik neni vyskolen pro toto letadlo');
    END IF;
END;
/

-- Triger 2 - Jestli letadlo nema splneny test, stane se prozatim nepouzitelny
CREATE OR REPLACE TRIGGER letadlo_zpusobile
AFTER UPDATE OF stav ON test
FOR EACH ROW
WHEN (NEW.stav = 'nesplneno')
BEGIN
    UPDATE letadlo
    SET aktivni = 0
    WHERE vyrobni_cislo = :NEW.vyrobni_cislo_letadla;
    DBMS_OUTPUT.PUT_LINE('Letadlo ' || :NEW.vyrobni_cislo_letadla || ' nema spleneno pozadavky pro jeho aktivni uzivani.');
END;
/

-- Uroven letadla podle doletu a pridava pocet ziskanych certifikatu
WITH pocet_certifikatu AS (
    SELECT vyrobni_cislo_letadla, COUNT(C.test_id) as cert_count
    FROM test T
    LEFT JOIN certifikat C ON T.id = C.test_id
    GROUP BY vyrobni_cislo_letadla
)
SELECT 
    L.vyrobni_cislo,
    M.nazev_modelu,
    -- Razeni podle doletu --
    CASE 
        WHEN L.dolet > 2000 THEN 'Dalkove letadlo'
        WHEN L.dolet BETWEEN 1000 AND 2000 THEN 'Stredni trat'
        ELSE 'Regionalni letadlo'
    END AS kategorie_doletu,
    -- Pouziti NVL specifiky pro Oracle (null value handling) --
    NVL(PC.cert_count, 0) as celkem_certifikatu
FROM letadlo L
JOIN model_letadla M ON L.model_id = M.id
LEFT JOIN pocet_certifikatu PC ON L.vyrobni_cislo = PC.vyrobni_cislo_letadla;

