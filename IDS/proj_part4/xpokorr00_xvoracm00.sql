-- Procedura 1. Projde vsechny testy letadla a vypise jejich vysledky --
CREATE OR REPLACE PROCEDURE vypis_testy_letadla (
    p_vyrobni_cislo IN letadlo.vyrobni_cislo%TYPE
)
AS
    CURSOR c_testy IS
        SELECT id, stav
        FROM test
        WHERE vyrobni_cislo_letadla = p_vyrobni_cislo;

    v_test c_testy%ROWTYPE;
BEGIN
    OPEN c_testy;
    LOOP
        FETCH c_testy INTO v_test;
        EXIT WHEN c_testy%NOTFOUND;

        DBMS_OUTPUT.PUT_LINE(
            'Test ID: ' || v_test.id || ', stav: ' || v_test.stav
        );
    END LOOP;
    CLOSE c_testy;
END;
/

BEGIN
    vypis_testy_letadla(1);
END;
/

-- Procedura 2. Vyhleda certifikat podle testu a nastavi ho jako archivovany. --
CREATE OR REPLACE PROCEDURE archivuj_certifikat (
    p_test_id IN certifikat.test_id%TYPE
)
AS
    v_certifikat certifikat%ROWTYPE;
BEGIN
    SELECT *
    INTO v_certifikat
    FROM certifikat
    WHERE test_id = p_test_id;

    UPDATE certifikat
    SET archivovano = 1
    WHERE test_id = p_test_id;

    DBMS_OUTPUT.PUT_LINE('Certifikat archivovan: ' || v_certifikat.nazev_certifikatu);

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Certifikat pro dany test neexistuje.');
END;
/

BEGIN
    archivuj_certifikat(1);
END;
