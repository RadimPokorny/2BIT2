-- Dotaz pro vypsani vsech letadel, vypisuje jejich hodnoty sloupců --
SELECT l.vyrobni_cislo, m.vyrobce, m.nazev_modelu, l.datum_vyroby
FROM letadlo l
JOIN model_letadla m ON l.model_id = m.id;

-- Vypsani vsech modelů letadel, ktere jsou evidovany v databazi
SELECT 
    m.nazev_modelu, 
    m.cislo_modelu, 
    l.vyrobni_cislo, 
    l.dolet
FROM model_letadla m
JOIN letadlo l ON m.id = l.model_id;

-- Vypisuje technikovy údaje, vcetne certifikatů kazdeho technika --
SELECT t.jmeno, t.prijmeni, c.nazev_certifikatu
FROM technik t
JOIN test test_tab ON t.rodne_cislo = test_tab.rodne_cislo
JOIN certifikat c ON test_tab.id = c.test_id;

-- Vypsani poctu vsech letadel na konkretniho vyrobce --
SELECT m.vyrobce, COUNT(l.vyrobni_cislo) AS pocet_letadel
FROM model_letadla m
LEFT JOIN letadlo l ON m.id = l.model_id
GROUP BY m.vyrobce;

